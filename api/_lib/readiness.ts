/**
 * Computes the deterministic Information Coverage score and Decision Readiness Score.
 * Guaranteed to be mathematically grounded rather than generated by LLM text.
 */
export function calculateDecisionReadiness(
  attributes: ExpectedAttributeCheck[],
  checklist: ChecklistItem[],
  conflicts: ConflictItem[] = []
): DecisionReadiness {
  const total = attributes.length > 0 ? attributes.length : 1;

  let coveredCount = 0;
  let partialCount = 0;
  let missingCount = 0;

  for (const attr of attributes) {
    if (attr.status === 'covered') {
      coveredCount++;
    } else if (attr.status === 'partially_covered') {
      partialCount++;
    } else {
      missingCount++;
    }
  }

  // Raw Information Coverage Percentage (0 to 100)
  const coveragePercent = Math.round(
    ((coveredCount * 1.0 + partialCount * 0.5) / total) * 100
  );

  // Deductions based on unresolved high-stakes risks
  const p1Pending = checklist.filter(c => c.priority === 'P1' && !c.completed);
  const p2Pending = checklist.filter(c => c.priority === 'P2' && !c.completed);
  const p3Pending = checklist.filter(c => c.priority === 'P3' && !c.completed);

  const p1Penalty = p1Pending.length * 14;
  const p2Penalty = p2Pending.length * 7;
  const p3Penalty = p3Pending.length * 3;
  const conflictPenalty = conflicts.filter(c => c.severity === 'high').length * 10;

  // Final Decision Readiness Score
  const rawScore = coveragePercent - (p1Penalty + p2Penalty + p3Penalty + conflictPenalty);
  const score = Math.max(5, Math.min(100, Math.round(rawScore)));

  let level: 'ready' | 'caution' | 'not_ready';
  let label: string;

  if (score >= 80) {
    level = 'ready';
    label = 'Ready to Apply (Standard Procedure)';
  } else if (score >= 50) {
    level = 'caution';
    label = 'Moderate Information Gaps (Verify Before Submit)';
  } else {
    level = 'not_ready';
    label = 'High Risk of Rejection (Critical Dark Spots)';
  }

  const summary = `${score}% Ready: ${p1Pending.length} critical P1 verification items, ${missingCount} unstated attributes across reviewed sources.`;

  return {
    score,
    level,
    label,
    coveredCount,
    partialCount,
    missingCount,
    p1PendingCount: p1Pending.length,
    summary,
  };
}
